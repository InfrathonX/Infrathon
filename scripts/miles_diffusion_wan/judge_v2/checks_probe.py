"""J1 probe gates: single-step training math against the independent fp32 oracle (precompute_train_oracle --mode probe).

(a) π_old at θ0 (= the step-0 lp_new of every probe pair; step 0 reuses its forward) vs the oracle lp:
    |Δlp| distribution (mean / p99 / max) — a wrong kernel (flow-SDE instead of Dance), a sign error in the score
    term, a missing CFG branch or σ-as-timestep moves lp by orders of magnitude more than kernel/precision choices;
(b) R4-style fp64 self-consistency of the probe's logged PPO terms;
(c) Adam step 1 on the oracle's top-|g| coordinates: sign(θ1−θ0) == −sign(g) fraction >= tau_sign and
    median(|θ1−θ0| / lr) in [0.8, 1.2] (Adam's first step is ≈ −lr·sign(g) where |g| >> eps).
Tolerances here are provisional (calibration: honest variants H1–H3 vs planted bugs).
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import torch
from safetensors import safe_open

TAU_LP_MEAN, TAU_LP_MAX = 1.5e-4, 6e-4  # S6: honest bf16 mean 6.2e-5 / max 1.5e-4 (same as R3)
# Signed error: honest bf16 π_old − fp32 oracle is systematically positive (+5.7e-5: the samples were generated by the
# bf16 engine, whose μ a bf16 trainer tracks more closely); fp32 gives ~0. Mean-shift errors in the transition math
# lower lp by mean(δ²)/2 (η-instead-of-η² in the trainer: −1.7e-4, all pairs negative). S6d.
SIGNED_MIN = -5e-5
TAU_SIGN = 0.9                          # provisional (OPCD used 0.9)
LR = 1e-5


def _gather(path_or_dir, names, numels, idx: torch.Tensor) -> torch.Tensor:
    """Values at flattened indices (sorted-name concatenation order) from a safetensors file or diffusers dir."""
    files = [Path(path_or_dir)] if Path(path_or_dir).is_file() else sorted(Path(path_or_dir).glob("*.safetensors"))
    handles = [safe_open(str(f), "pt") for f in files]
    where = {}
    for h in handles:
        for k in h.keys():
            where[k] = h
    out = torch.empty(idx.numel(), dtype=torch.float64)
    order = torch.argsort(idx)
    sidx = idx[order]
    off = 0
    pos = 0
    for n, m in zip(names, numels):
        hi = torch.searchsorted(sidx, off + m)
        if hi > pos:
            t = where[n].get_tensor(n).flatten().double()
            out[order[pos:hi]] = t[sidx[pos:hi] - off]
            pos = int(hi)
        off += m
    return out


def check_probe(oracle_dir: Path, pair_dir: Path, theta1: Path, theta0_dir: Path) -> dict:
    res = {}
    orc = json.load(open(oracle_dir / "train_oracle_probe.json"))
    ev = []
    for f in sorted(pair_dir.glob("rollout*_rank*.jsonl")):
        ev += [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    steps = [e for e in ev if e["kind"] == "step"]
    sd = []
    for e in steps:
        key = f"{e['group']}|{e['j']}|{e['k']}"
        if key in orc["per_pair"]:
            sd.append(e["lp_old"] - orc["per_pair"][key]["lp"])
    d = [abs(x) for x in sd]
    dt = torch.tensor(d, dtype=torch.float64)
    signed = float(torch.tensor(sd, dtype=torch.float64).mean()) if sd else None
    res["J1a_pi_old_vs_oracle"] = {
        "ok": len(d) == len(orc["per_pair"]) and float(dt.mean()) <= TAU_LP_MEAN and float(dt.max()) <= TAU_LP_MAX
        and signed >= SIGNED_MIN,
        "n": len(d), "mean": float(dt.mean()) if d else None, "p99": float(torch.quantile(dt, 0.99)) if d else None,
        "max": float(dt.max()) if d else None, "signed_mean": signed}
    worst = 0.0
    for e in steps:
        r = math.exp(e["lp_new"] - e["lp_old"])
        a = e["adv"]
        loss = max(-a * r, -a * min(max(r, 1 - 1e-4), 1 + 1e-4))
        worst = max(worst, abs(r - e["ratio"]), abs(loss - e["loss"]))
    res["J1b_self_consistency"] = {"ok": worst <= 1e-6, "worst": worst}
    top = torch.load(oracle_dir / "train_oracle_probe.pt", weights_only=True)
    idx, sgn = top["top_idx"].long(), top["top_sign"].double()
    names, numels = orc["names"], orc["numels"]
    t1 = _gather(theta1, names, numels, idx)
    t0 = _gather(theta0_dir, names, numels, idx)
    dlt = t1 - t0
    moved = dlt != 0
    agree = (torch.sign(dlt[moved]) == -sgn[moved]).double().mean() if moved.any() else torch.tensor(0.0)
    ratio = (dlt.abs() / LR).median()
    res["J1c_adam_sign"] = {"ok": float(agree) >= TAU_SIGN and bool(moved.double().mean() > 0.5),
                            "agree": float(agree), "moved_frac": float(moved.double().mean()), "n_coords": int(idx.numel())}
    res["J1d_adam_magnitude"] = {"ok": 0.8 <= float(ratio) <= 1.2, "median_abs_dtheta_over_lr": float(ratio)}
    return res


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--oracle", required=True)
    ap.add_argument("--pairs", required=True)
    ap.add_argument("--theta1", required=True)
    ap.add_argument("--theta0", default="/models/Wan2.2-TI2V-5B-Diffusers/transformer")
    a = ap.parse_args()
    print(json.dumps(check_probe(Path(a.oracle), Path(a.pairs), Path(a.theta1), Path(a.theta0)), indent=1))
