#!/usr/bin/env python3
"""Judge-side check of an OPD run against the SGLang audit log.

Inputs: the audit JSONL written by ``opd_audit_hook`` inside every SGLang process,
the per-step training dumps, the training data file whose line order fixes which rows
each round must use, and the pinned tokenizer / teacher path. It imports no candidate
code and fails closed on missing evidence.

Engines are told apart by the model they serve: an engine launched on the pinned
teacher snapshot is a teacher engine; every other engine is a student engine. A run
may have no teacher engine at all (teacher inside Megatron).

Checks
  E  engines    teacher engines never receive a weight update; a student engine serves
                the pinned student snapshot or received Miles' initial weight push
                before its first generation
  W1 prompts    every student generation's prompt ids == the rendered prompt of its
                assigned training row (chat template, template kwargs)
  W2 sampling   a student engine receives only generation requests with the contract's
                sampling parameters: temperature 1, top_p 1, no top-k/min-p truncation,
                max_new_tokens == max_response_len, no ignore_eos, no session, no
                top-logprob / token-id-logprob requests (return_logprob is allowed);
                in particular no scoring (prefill-only) requests
  W3 work       every dumped training sequence == prompt+output of exactly one completed
                generation; every generation trained exactly once; exactly `per_round`
                per step; step s uses rows [s*n, (s+1)*n)
  W4 staleness  every token of a sample trained at step s was generated by weight
                version >= s - max_lag (version v = published after step v-1); no
                sample finished after step s's own update or during a publication
  W5 publish    per student engine, one publication per step (plus the initial push)
  W6 old lp     the dumped old_logprobs come from a training-side forward, not from the
                sampling engine: over the first output tokens of every trained sample, the
                share of (non-zero) values bit-identical to the log-probs the engine
                returned must stay at or below --max-engine-lp-equal (different kernels
                never agree bit for bit on most tokens; a copy agrees on all of them)
  T             wall clock from the first student generation dispatch to the end of the
                last publication, from the audit log only, minus any evaluator-owned
                intervals inside that window (--exclude-intervals: the provenance hook's
                copies and digests of the weights); must be positive
"""

import argparse
import bisect
import glob
import json
import os
import re
import struct
from collections import defaultdict

LP_HEAD = 32  # = opd_audit_hook.LP_HEAD: engine log-probs recorded per generation

HEALTH = "HEALTH_CHECK"
ENGINE_KINDS = ("engine", "dispatch", "final", "weights", "pause", "continue")


def load_audit(audit_dir):
    recs = []
    files = sorted(glob.glob(os.path.join(audit_dir, "*.jsonl")))
    if not files:
        raise AssertionError(f"no audit files in {audit_dir}")
    for f in files:
        with open(f) as fh:
            for line in fh:
                line = line.strip()
                if line:
                    recs.append(json.loads(line))
    return recs


def render_rows(data_path, tokenizer, template_kwargs):
    rows = []
    with open(data_path) as fh:
        for line in fh:
            d = json.loads(line)
            text = tokenizer.apply_chat_template(d["content"], tokenize=False, add_generation_prompt=True, **template_kwargs)
            rows.append((d.get("row_id"), tuple(tokenizer.encode(text, add_special_tokens=False))))
    return rows


def load_dumps(pattern):
    """step -> [(token tuple, response length, float32 head of old_logprobs)] from the task's
    step_{s:03d}_rank_{r}.pt dumps."""
    import torch

    steps = defaultdict(list)
    for path in sorted(glob.glob(pattern)):
        m = re.search(r"step_(\d+)_rank_(\d+)", path)
        if not m:
            continue
        d = torch.load(path, map_location="cpu", weights_only=True)
        olds = d.get("old_logprobs") or [None] * len(d["tokens"])
        for tok, R, old in zip(d["tokens"], d["response_lengths"], olds):
            seq = tuple(int(x) for x in (tok.tolist() if hasattr(tok, "tolist") else tok))
            head = old[:LP_HEAD].to(torch.float32).tolist() if torch.is_tensor(old) else None
            steps[int(m.group(1))].append((seq, int(R), head))
    if not steps:
        raise AssertionError(f"no training dumps match {pattern}")
    return steps


def same_path(a, b):
    return bool(a) and os.path.realpath(str(a).rstrip("/")) == os.path.realpath(str(b).rstrip("/"))


def publications(wcalls, disp_times, markers, t_first):
    """Split one engine's successful weight calls into publications.

    A publication is a run of successful weight calls; a new one starts whenever, since
    the previous call, a generation was dispatched to this engine, generation was paused /
    continued, or the engine's version label changed. Calls that end before the first
    training generation are the initial push. Returns (initial push call count,
    [(first call number, last call number, t_end)] of the later publications)."""
    def any_between(times, a, b):
        return bisect.bisect_right(times, a) < bisect.bisect_left(times, b)

    groups, prev = [], None
    for idx, w in enumerate(wcalls):
        if prev is None or any_between(disp_times, prev["t_end"], w["t_start"]) \
                or any_between(markers, prev["t_end"], w["t_start"]) \
                or prev.get("server_weight_version") != w.get("server_weight_version"):
            groups.append([])
        groups[-1].append((idx + 1, w))  # call number = count after this call
        prev = w
    n_pre = sum(len(g) for g in groups if g[-1][1]["t_end"] <= t_first)
    pubs = [(g[0][0], g[-1][0], g[-1][1]["t_end"]) for g in groups if g[-1][1]["t_end"] > t_first]
    return n_pre, pubs


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--audit-dir", required=True)
    ap.add_argument("--dumps", required=True, help="glob of step_{step}_rank_{r}.pt training dumps")
    ap.add_argument("--data", required=True, help="training jsonl; line order fixes the row->round assignment")
    ap.add_argument("--tokenizer", required=True)
    ap.add_argument("--student-model-path", required=True, help="pinned student snapshot (contract student_hf)")
    ap.add_argument("--teacher-model-path", required=True, help="pinned teacher snapshot (contract teacher_hf)")
    ap.add_argument("--rounds", type=int, required=True)
    ap.add_argument("--per-round", type=int, required=True)
    ap.add_argument("--max-new-tokens", type=int, required=True, help="contract max_response_len")
    ap.add_argument("--max-lag", type=int, default=1)
    ap.add_argument("--max-engine-lp-equal", type=float, default=0.5,
                    help="W6: largest share of old_logprobs bit-identical to the engine's log-probs")
    ap.add_argument("--min-lp-compared", type=int, default=200, help="W6: judge only with at least this many tokens")
    ap.add_argument("--temperature", type=float, default=1.0)
    ap.add_argument("--top-p", type=float, default=1.0)
    ap.add_argument("--template-kwargs", default='{"enable_thinking": false}')
    ap.add_argument("--exclude-intervals", default=None,
                    help="JSON file with [[t_start, t_end], ...] of evaluator-owned work to take out of T")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(args.tokenizer)
    rows = render_rows(args.data, tok, json.loads(args.template_kwargs))
    need = args.rounds * args.per_round
    if len(rows) < need:
        raise AssertionError(f"training file has {len(rows)} rows, quota needs {need}")
    prompt_to_row = {}
    for idx, (_, ids) in enumerate(rows[:need]):
        prompt_to_row.setdefault(ids, []).append(idx)

    recs = [r for r in load_audit(args.audit_dir) if r.get("kind") in ENGINE_KINDS]
    ekey = lambda r: f"{r.get('pid')}:{r.get('port')}"
    engines = {}
    for r in recs:
        e = engines.setdefault(ekey(r), {"model_path": r.get("model_path"), "requests": 0, "weight_calls": 0})
        e["requests"] += r["kind"] == "dispatch"
        e["weight_calls"] += r["kind"] == "weights"
    for e in engines.values():
        e["role"] = "teacher" if same_path(e["model_path"], args.teacher_model_path) else "student"
    student = lambda r: engines[ekey(r)]["role"] == "student"
    issues = defaultdict(list)

    # ---- E teacher engines ---------------------------------------------------
    for k, e in engines.items():
        if e["role"] == "teacher" and e["weight_calls"]:
            issues["E"].append(f"teacher engine {k} received {e['weight_calls']} weight-update calls")

    # ---- W2 sampling ----------------------------------------------------------
    gens = {}
    for d in recs:
        if d["kind"] != "dispatch" or not student(d) or str(d.get("rid", "")).startswith(HEALTH):
            continue
        rid, s = d["rid"], d.get("sampling") or {}
        where = f"student engine {ekey(d)} ({d.get('model_path')}) rid {rid}"
        if d.get("top_logprobs_num") or d.get("token_ids_logprob"):
            issues["W2"].append(f"{where}: top-logprob/token-id-logprob request")
        if d.get("session"):
            issues["W2"].append(f"{where}: session request")
        if s.get("max_new_tokens") != args.max_new_tokens:
            issues["W2"].append(f"{where}: max_new_tokens {s.get('max_new_tokens')} (a scoring or non-contract request; "
                                f"only the pinned teacher's engine may score)")
            continue
        top_k_off = s.get("top_k") in (-1, None, 0) or (s.get("top_k") or 0) >= (1 << 30)  # SGLang's "disabled" sentinel
        if s.get("temperature") != args.temperature or s.get("top_p") != args.top_p or not top_k_off \
                or s.get("min_p") not in (0, 0.0, None) or s.get("ignore_eos"):
            issues["W2"].append(f"{where}: sampling {s}")
        gens[(ekey(d), rid)] = d
    finals = {(ekey(r), r["rid"]): r for r in recs if r["kind"] == "final" and student(r) and r.get("rid")}
    t_first = min((d["t"] for d in gens.values()), default=float("inf"))

    # ---- E student engines, W5 publications -----------------------------------
    gen_engines = sorted({k for k, _ in gens})
    version_of, pubs_of, n_pre_of = {}, {}, {}
    for k in gen_engines:
        mine = lambda r: ekey(r) == k
        wcalls = sorted([r for r in recs if r["kind"] == "weights" and mine(r) and r.get("success")], key=lambda r: r["t_start"])
        disp = sorted(r["t"] for r in recs if r["kind"] == "dispatch" and mine(r) and not str(r.get("rid", "")).startswith(HEALTH))
        marks = sorted(r["t"] for r in recs if r["kind"] in ("pause", "continue") and mine(r))
        n_pre, pubs = publications(wcalls, disp, marks, t_first)
        n_pre_of[k], pubs_of[k] = n_pre, pubs
        if not same_path(engines[k]["model_path"], args.student_model_path) and n_pre == 0:
            issues["E"].append(f"student engine {k} serves {engines[k]['model_path']} and got no weight push before sampling")
        if len(pubs) != args.rounds:
            issues["W5"].append(f"student engine {k}: {len(pubs)} publications after the first training generation; "
                                f"need exactly {args.rounds} (one per step)")

        def version(count, pubs=pubs, n_pre=n_pre):
            """(completed publications, inside a partial publication) when `count` weight calls had completed"""
            if count is None:
                return None, True
            done = sum(1 for _, b, _ in pubs if count >= b)
            return done, any(a <= count < b for a, b, _ in pubs) or 0 < count < n_pre

        version_of[k] = version
    if not gens:
        issues["W3"].append("no student generation requests were recorded")

    # ---- W1 prompts, W3 work, W4 staleness ------------------------------------
    by_seq = defaultdict(list)
    for key, d in gens.items():
        f = finals.get(key)
        aborted = isinstance(f, dict) and isinstance(f.get("finish_reason"), dict) and f["finish_reason"].get("type") == "abort"
        if f is None or f.get("output_ids") is None or aborted or f.get("error") not in (None, "GeneratorExit"):
            issues["W3"].append(f"rid {key[1]}: dispatched but no completed output")
            continue
        prompt = tuple(d["input_ids"] or ())
        if prompt not in prompt_to_row:
            issues["W1"].append(f"rid {key[1]}: prompt matches no assigned training row")
        by_seq[prompt + tuple(f["output_ids"])].append(key)

    steps = load_dumps(args.dumps)
    extra = sorted(s for s in steps if not 0 <= s < args.rounds)
    if extra:
        issues["W3"].append(f"dumps for steps {extra[:5]} outside 0..{args.rounds - 1}")
    used, used_rows, lags = set(), defaultdict(int), []
    lp_cmp = [0, 0]  # compared tokens, bit-identical to the engine's log-prob
    for s in range(args.rounds):
        samples = steps.get(s, [])
        if len(samples) != args.per_round:
            issues["W3"].append(f"step {s}: {len(samples)} trained samples, need {args.per_round}")
        for seq, R, old_head in samples:
            cands = [k for k in by_seq.get(seq, []) if k not in used]
            if not cands:
                issues["W3"].append(f"step {s}: a trained sequence matches no unused completed generation")
                continue
            key = cands[0]
            used.add(key)
            eng_head = finals[key].get("out_lp_head")
            if old_head and eng_head:
                for a_, b_ in zip(old_head, eng_head):
                    if abs(b_) > 1e-6:  # near-certain tokens can round to 0 on both sides
                        lp_cmp[0] += 1
                        lp_cmp[1] += struct.pack("f", a_) == struct.pack("f", b_)
            row_ids = prompt_to_row.get(tuple(gens[key]["input_ids"]), [])
            row = next((i for i in row_ids if s * args.per_round <= i < (s + 1) * args.per_round), None)
            if row is None:
                issues["W3"].append(f"step {s}: sample from row(s) {row_ids[:3]} outside this step's assigned rows")
            else:
                used_rows[row] += 1
            v0, in0 = version_of[key[0]](gens[key]["weight_calls"])
            v1, in1 = version_of[key[0]](finals[key].get("weight_calls"))
            if in0 or in1:
                issues["W4"].append(f"step {s} rid {key[1]}: generated during a partial publication")
            if v0 is None or v1 is None:
                continue
            lags.append(s - v0)
            if s - v0 > args.max_lag:
                issues["W4"].append(f"step {s} rid {key[1]}: oldest token from version {v0} (lag {s - v0})")
            if v1 > s:
                issues["W4"].append(f"step {s} rid {key[1]}: finished under version {v1}, after this step's update")
    unused = [k for k in gens if k not in used and finals.get(k) and finals[k].get("output_ids") is not None]
    if unused:
        issues["W3"].append(f"{len(unused)} completed student generations were never trained on (oversampling/discard)")
    dup = [r for r, c in used_rows.items() if c > 1]
    if dup:
        issues["W3"].append(f"{len(dup)} training rows used more than once")
    missing = need - len(used_rows)
    if missing:
        issues["W3"].append(f"{missing} assigned training rows never used")

    equal_frac = lp_cmp[1] / lp_cmp[0] if lp_cmp[0] else None
    if lp_cmp[0] >= args.min_lp_compared and equal_frac > args.max_engine_lp_equal:
        issues["W6"].append(f"{equal_frac:.1%} of {lp_cmp[0]} compared old_logprobs are bit-identical to the "
                            "log-probs the sampling engine returned: old log-probs must come from a training-side forward")

    t0 = min((d["t"] for d in gens.values()), default=None)
    t1 = max((p[-1][2] for p in pubs_of.values() if p), default=None)
    excluded = 0.0
    if args.exclude_intervals and t0 and t1:
        spans = sorted(json.load(open(args.exclude_intervals)))
        end = t0
        for a, b in spans:  # union of the intervals, clipped to [t0, t1]
            a, b = max(a, end, t0), min(b, t1)
            if b > a:
                excluded += b - a
                end = b
    wall = (t1 - t0 - excluded) if (t0 and t1) else None
    if wall is None or not wall > 0:
        issues["T"].append(f"no positive timed window: first request {t0}, end of the last publication {t1}, "
                           f"excluded {excluded:.3f} s")
    report = {
        "passed": not any(issues.values()),
        "issues": {k: v[:20] + ([f"... {len(v) - 20} more"] if len(v) > 20 else []) for k, v in issues.items()},
        "issue_counts": {k: len(v) for k, v in issues.items()},
        "engines": engines,
        "student_generations": len(gens),
        "teacher_requests": sum(e["requests"] for e in engines.values() if e["role"] == "teacher"),
        "initial_push_calls": n_pre_of,
        "publications": {k: len(v) for k, v in pubs_of.items()},
        "calls_per_publication": sorted({b - a + 1 for p in pubs_of.values() for a, b, _ in p}),
        "trained_samples": sum(len(v) for v in steps.values()),
        "rows_used": len(used_rows),
        "lag_histogram": {str(k): lags.count(k) for k in sorted(set(lags))},
        "old_lp_compared_tokens": lp_cmp[0],
        "old_lp_engine_equal_frac": equal_frac,
        "wall_clock_seconds": wall,
        "wall_clock_raw_seconds": (t1 - t0) if (t0 and t1) else None,
        "excluded_seconds": excluded,
        "t_start": t0,
        "t_end": t1,
    }
    print(json.dumps(report, indent=2))
    if args.out:
        with open(args.out, "w") as fh:
            json.dump(report, fh, indent=2)
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
