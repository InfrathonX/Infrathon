#!/usr/bin/env python3
"""Judge-side check of an OPCD run against the SGLang audit log (rules R1-R4).

Inputs: the audit JSONL written by ``opcd_audit_hook`` inside the SGLang
processes, the per-step training dumps, the training data file whose line order
fixes which rows each round must use, and the pinned tokenizer/context.
It imports no candidate code and fails closed on missing evidence.

Checks
  W1 prompts   every student generation's prompt ids == the rendered student
               prompt of its assigned training row (no context, no rewrite)
  W2 sampling  temperature 1, top_p 1, no top-k/min-p truncation, no session,
               and no top-logprob / token-id-logprob requests to the student
               engine at all (R1: the top-k set must come from the trainer)
  W3 work      every dumped training sequence == prompt+output of exactly one
               completed generation; every generation trained exactly once;
               exactly `per_round` per step; step s uses rows [s*n, (s+1)*n)
  W4 staleness every token of a sample trained at step s was generated by
               weight version s or s-1 (R2); nothing trained before it existed
  W5 publish   one publication per step (plus the initial push)
  T            wall clock from the first student generation dispatch to the end
               of the last publication, from the audit log only, minus any
               evaluator-owned intervals inside that window (--exclude-intervals:
               the provenance hook's copies of the served weights and its digests);
               must be positive
"""

import argparse
import glob
import json
import os
import re
from collections import defaultdict

HEALTH = "HEALTH_CHECK"


def load_audit(audit_dir):
    recs = []
    files = sorted(glob.glob(os.path.join(audit_dir, "*.jsonl")))
    if not files:
        raise AssertionError(f"no audit files in {audit_dir}")
    for f in files:
        with open(f) as fh:
            for line in fh:
                line = line.strip()
                if line:
                    recs.append(json.loads(line))
    return recs


def render_rows(data_path, tokenizer, template_kwargs):
    rows = []
    with open(data_path) as fh:
        for line in fh:
            d = json.loads(line)
            text = tokenizer.apply_chat_template(d["content"], tokenize=False, add_generation_prompt=True, **template_kwargs)
            rows.append((d.get("row_id"), tuple(tokenizer.encode(text, add_special_tokens=False))))
    return rows


def context_prefix(tokenizer, context, template_kwargs):
    kw = dict(tokenize=False, add_generation_prompt=True, **template_kwargs)
    probe = [{"role": "user", "content": "probe"}]
    s = tokenizer.apply_chat_template(probe, **kw)
    t = tokenizer.apply_chat_template([{"role": "system", "content": context}, *probe], **kw)
    s_ids, t_ids = tokenizer.encode(s, add_special_tokens=False), tokenizer.encode(t, add_special_tokens=False)
    return tuple(t_ids[: len(t_ids) - len(s_ids)])


def load_dumps(pattern):
    """Per-step training records: the task's step_{s:03d}_rank_{r}.pt (top-level keys) or Miles'
    --save-debug-train-data rollout_{s}_rank_{r}.pt (keys under rollout_data)."""
    import torch

    steps = defaultdict(list)
    for path in sorted(glob.glob(pattern)):
        m = re.search(r"(?:step|rollout)_(\d+)_rank_(\d+)", path)
        if not m:
            continue
        d = torch.load(path, map_location="cpu", weights_only=True)
        rd = d.get("rollout_data", d)
        for tok, R in zip(rd["tokens"], rd["response_lengths"]):
            seq = tuple(int(x) for x in (tok.tolist() if hasattr(tok, "tolist") else tok))
            steps[int(m.group(1))].append((seq, int(R)))
    if not steps:
        raise AssertionError(f"no training dumps match {pattern}")
    return steps


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--audit-dir", required=True)
    ap.add_argument("--dumps", required=True, help="glob of rollout_{step}_rank_{r}.pt training dumps")
    ap.add_argument("--data", required=True, help="training jsonl; line order fixes the row->round assignment")
    ap.add_argument("--tokenizer", required=True)
    ap.add_argument("--context-file", required=True)
    ap.add_argument("--student-model-path", required=True, help="model_path the student engine was launched with")
    ap.add_argument("--rounds", type=int, required=True)
    ap.add_argument("--per-round", type=int, required=True)
    ap.add_argument("--max-lag", type=int, default=1)
    ap.add_argument("--template-kwargs", default='{"enable_thinking": false}')
    ap.add_argument("--exclude-intervals", default=None,
                    help="JSON file with [[t_start, t_end], ...] of evaluator-owned work to take out of T")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    from transformers import AutoTokenizer

    tk = json.loads(args.template_kwargs)
    tok = AutoTokenizer.from_pretrained(args.tokenizer)
    ctx = context_prefix(tok, open(args.context_file, encoding="utf-8").read().strip(), tk)
    rows = render_rows(args.data, tok, tk)
    need = args.rounds * args.per_round
    if len(rows) < need:
        raise AssertionError(f"training file has {len(rows)} rows, quota needs {need}")
    prompt_to_row = {}
    for idx, (_, ids) in enumerate(rows[:need]):
        prompt_to_row.setdefault(ids, []).append(idx)

    recs = load_audit(args.audit_dir)
    student = lambda r: r.get("model_path") == args.student_model_path
    issues = defaultdict(list)

    # ---- publications (W5) --------------------------------------------------
    # A publication is a run of successful weight calls on the student engine.
    # A new one starts whenever, since the previous call, a student generation was
    # dispatched, generation was paused/continued, or the engine's version label
    # changed. Calls before the first training generation are the initial push of
    # the pinned weights (version 0). After that there must be exactly one
    # publication per optimizer step: splitting one update into several (to make
    # data look fresher) or skipping/merging updates both change that count.
    wcalls = sorted([r for r in recs if r["kind"] == "weights" and student(r) and r.get("success")], key=lambda r: r["t_start"])
    dispatches = [r for r in recs if r["kind"] == "dispatch" and student(r) and not str(r.get("rid", "")).startswith(HEALTH)]
    finals = {r["rid"]: r for r in recs if r["kind"] == "final" and student(r) and r.get("rid")}
    markers = sorted(r["t"] for r in recs if r["kind"] in ("pause", "continue") and student(r))
    disp_times = sorted(r["t"] for r in dispatches)
    t_first = disp_times[0] if disp_times else float("inf")

    def any_between(times, a, b):
        import bisect
        return bisect.bisect_right(times, a) < bisect.bisect_left(times, b)

    groups, prev = [], None
    for idx, w in enumerate(wcalls):
        new_group = prev is None or any_between(disp_times, prev["t_end"], w["t_start"]) \
            or any_between(markers, prev["t_end"], w["t_start"]) \
            or prev.get("server_weight_version") != w.get("server_weight_version")
        if new_group:
            groups.append([])
        groups[-1].append((idx + 1, w))  # call number = count after this call
        prev = w
    pre = [g for g in groups if g[-1][1]["t_end"] <= t_first]
    pubs = [g for g in groups if g[-1][1]["t_end"] > t_first]
    n_pre = sum(len(g) for g in pre)
    bounds = [(g[0][0], g[-1][0]) for g in pubs]  # (first call number, last call number)

    def version(count):
        """weights in force when `count` weight calls had completed"""
        if count is None:
            return None, True
        done = sum(1 for a, b in bounds if count >= b)
        inside = any(a <= count < b for a, b in bounds) or 0 < count < n_pre
        return done, inside

    if len(pubs) != args.rounds:
        issues["W5"].append(f"{len(pubs)} publications after the first training generation; need exactly {args.rounds} (one per step)")

    # ---- W2 sampling + R1 ----------------------------------------------------
    gens = {}
    for d in dispatches:
        mnt = (d.get("sampling") or {}).get("max_new_tokens")
        if d.get("top_logprobs_num") or d.get("token_ids_logprob"):
            issues["W2"].append(f"rid {d['rid']}: top-logprob/token-id-logprob request to the student engine (R1)")
        if d.get("session"):
            issues["W2"].append(f"rid {d['rid']}: session request")
        if mnt == 0:
            issues["W2"].append(f"rid {d['rid']}: scoring (max_new_tokens=0) request to the student engine")
            continue
        s = d.get("sampling") or {}
        top_k_off = s.get("top_k") in (-1, None, 0) or (s.get("top_k") or 0) >= (1 << 30)  # SGLang's "disabled" sentinel
        if s.get("temperature") != 1.0 or s.get("top_p") != 1.0 or not top_k_off or s.get("min_p") not in (0, 0.0, None):
            issues["W2"].append(f"rid {d['rid']}: sampling {s}")
        gens[d["rid"]] = d

    # ---- W1 prompts, W3 work -------------------------------------------------
    by_seq = defaultdict(list)
    for rid, d in gens.items():
        f = finals.get(rid)
        aborted = isinstance(f, dict) and isinstance(f.get("finish_reason"), dict) and f["finish_reason"].get("type") == "abort"
        if f is None or f.get("output_ids") is None or aborted or f.get("error") not in (None, "GeneratorExit"):
            issues["W3"].append(f"rid {rid}: dispatched but no completed output")
            continue
        prompt = tuple(d["input_ids"] or ())
        if prompt[: len(ctx)] == ctx:
            issues["W1"].append(f"rid {rid}: context prefix in the student prompt")
        if prompt not in prompt_to_row:
            issues["W1"].append(f"rid {rid}: prompt matches no assigned training row")
        by_seq[prompt + tuple(f["output_ids"])].append(rid)

    steps = load_dumps(args.dumps)
    used_rids, used_rows = set(), defaultdict(int)
    lags = []
    for s in range(args.rounds):
        samples = steps.get(s, [])
        if len(samples) != args.per_round:
            issues["W3"].append(f"step {s}: {len(samples)} trained samples, need {args.per_round}")
        for seq, R in samples:
            cands = [r for r in by_seq.get(seq, []) if r not in used_rids]
            if not cands:
                issues["W3"].append(f"step {s}: a trained sequence matches no unused completed generation")
                continue
            rid = cands[0]
            used_rids.add(rid)
            prompt = tuple(gens[rid]["input_ids"])
            row_ids = prompt_to_row.get(prompt, [])
            row = next((i for i in row_ids if s * args.per_round <= i < (s + 1) * args.per_round), None)
            if row is None:
                issues["W3"].append(f"step {s}: sample from row(s) {row_ids[:3]} outside this step's assigned rows")
            else:
                used_rows[row] += 1
            v0, in0 = version(gens[rid]["weight_calls"])
            v1, in1 = version(finals[rid]["weight_calls"])
            if in0 or in1:
                issues["W4"].append(f"step {s} rid {rid}: generated during a partial publication")
            lags.append(s - v0)
            if s - v0 > args.max_lag:
                issues["W4"].append(f"step {s} rid {rid}: oldest token from version {v0} (lag {s - v0})")
            if v1 > s:
                issues["W4"].append(f"step {s} rid {rid}: finished under version {v1}, after this step's update")
    unused = [r for r in gens if r not in used_rids and finals.get(r) and finals[r].get("output_ids") is not None]
    if unused:
        issues["W3"].append(f"{len(unused)} completed student generations were never trained on (oversampling/discard)")
    dup = [r for r, c in used_rows.items() if c > 1]
    if dup:
        issues["W3"].append(f"{len(dup)} training rows used more than once")
    missing = need - len(used_rows)
    if missing:
        issues["W3"].append(f"{missing} assigned training rows never used")

    t0 = min((d["t"] for d in gens.values()), default=None)
    t1 = pubs[-1][-1][1]["t_end"] if pubs else None
    excluded = 0.0
    if args.exclude_intervals and t0 and t1:
        spans = sorted(json.load(open(args.exclude_intervals)))
        end = t0
        for a, b in spans:  # union of the intervals, clipped to [t0, t1]
            a, b = max(a, end, t0), min(b, t1)
            if b > a:
                excluded += b - a
                end = b
    wall = (t1 - t0 - excluded) if (t0 and t1) else None
    if wall is None or not wall > 0:
        issues["T"].append(f"no positive timed window: first student generation {t0}, end of the last publication "
                           f"{t1}, excluded {excluded:.3f} s")
    report = {
        "passed": not any(issues.values()),
        "issues": {k: v[:20] + ([f"... {len(v) - 20} more"] if len(v) > 20 else []) for k, v in issues.items()},
        "issue_counts": {k: len(v) for k, v in issues.items()},
        "student_generations": len(gens),
        "initial_push_calls": n_pre,
        "publications": len(pubs),
        "calls_per_publication": sorted({len(p) for p in pubs}),
        "trained_samples": sum(len(v) for v in steps.values()),
        "rows_used": len(used_rows),
        "lag_histogram": {str(k): lags.count(k) for k in sorted(set(lags))},
        "wall_clock_seconds": wall,
        "wall_clock_raw_seconds": (t1 - t0) if (t0 and t1) else None,
        "excluded_seconds": excluded,
        "t_start": t0,
        "t_end": t1,
    }
    print(json.dumps(report, indent=2))
    if args.out:
        with open(args.out, "w") as fh:
            json.dump(report, fh, indent=2)
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
